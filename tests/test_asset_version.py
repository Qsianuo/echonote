"""The static-asset cache key is derived from content, and must prove it.

Two releases in a row shipped a key that had been bumped in ``index.html`` but
not in ``app.js`` (``c9fd883``, ``db33ef4``). The failure is silent in the worst
way: the browser keeps serving the old ``pcm-worklet.js``, so the recording
chain behaves like code that no longer exists — the same class of confusion as
the zero-fill "buzzing" bug. These tests turn that memory lapse into a red test
instead of a support ticket.

The key itself is regenerated by ``tools/bump_asset_version.py``.
"""

from __future__ import annotations

import importlib.util
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
WEB = ROOT / "web"
TOOL = ROOT / "tools" / "bump_asset_version.py"

IMPORT_WITH_VERSION = re.compile(r"""from\s+['"]\./([\w.-]+)\?v=([\w.-]+)['"]""")
HTML_WITH_VERSION = re.compile(r"""(?:href|src)=['"]([\w.-]+)\?v=([\w.-]+)['"]""")


def _load_tool():
    spec = importlib.util.spec_from_file_location("bump_asset_version", TOOL)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def test_no_carrier_still_holds_an_old_key():
    tool = _load_tool()
    stale = tool.stale_carriers(WEB)
    assert not stale, (
        "these files carry an asset key that no longer matches the asset content: "
        + ", ".join(p.name for p in stale)
        + " — run: python tools/bump_asset_version.py"
    )


def test_key_does_not_depend_on_line_endings(tmp_path):
    """A Windows clone is CRLF, CI is LF; both must derive the same key."""
    tool = _load_tool()
    for path in tool.hashed_assets(WEB):
        raw = path.read_bytes().replace(b"\r\n", b"\n")
        (tmp_path / path.name).write_bytes(raw.replace(b"\n", b"\r\n"))
    assert tool.compute_key(tmp_path) == tool.compute_key(WEB)


def test_every_asset_html_references_actually_exists():
    html = (WEB / "index.html").read_text(encoding="utf-8")
    referenced = {name for name, _ in HTML_WITH_VERSION.findall(html)}
    assert referenced, "index.html stopped versioning its assets — cache busting is off"
    for name in sorted(referenced):
        assert (WEB / name).is_file(), f"index.html points at a missing asset: {name}"


def test_native_modules_are_imported_through_exactly_one_url():
    """Two keys for one module = two module instances, silently.

    ``native-vad.js`` was once imported as ``?v=…l`` from native-boot and
    ``?v=…g`` from native-engine: two Module records, two ``MODES`` objects, two
    ``Segmenter`` classes. Native mode only, so no desktop test noticed.
    """
    seen: dict[str, set[str]] = {}
    for name in ("native-boot.js", "native-engine.js"):
        text = (WEB / name).read_text(encoding="utf-8")
        for module, key in IMPORT_WITH_VERSION.findall(text):
            seen.setdefault(module, set()).add(key)
    assert seen, "no versioned native imports found — the guard would be vacuous"
    duplicated = {module: keys for module, keys in seen.items() if len(keys) > 1}
    assert not duplicated, f"modules imported under more than one key: {duplicated}"
